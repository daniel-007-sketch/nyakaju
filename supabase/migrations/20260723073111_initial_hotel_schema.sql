  on public.bookings (lower(guest_email), created_at desc);

create index bookings_recent_idx
  on public.bookings (created_at desc);

create index bookings_status_arrival_idx
  on public.bookings (status, arrival_date);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.set_booking_timestamps()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  if new.status is distinct from old.status then
    new.status_updated_at := now();
  end if;
  return new;
end;
$$;

