create table public.room_types (
  id bigint generated by default as identity primary key,
  slug text not null,
  name text not null,
  description text not null default '',
  nightly_rate numeric(10, 2) not null,
  currency text not null default 'USD',
  total_units integer not null,
  beds smallint not null default 1,
  bathrooms smallint not null default 1,
  is_active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint room_types_slug_key unique (slug),
  constraint room_types_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint room_types_name_not_blank check (btrim(name) <> ''),
  constraint room_types_rate_positive check (nightly_rate > 0),
  constraint room_types_currency_format check (currency ~ '^[A-Z]{3}$'),
  constraint room_types_units_positive check (total_units > 0),
  constraint room_types_beds_positive check (beds > 0),
  constraint room_types_bathrooms_positive check (bathrooms > 0)
);

create table public.room_images (
  id bigint generated by default as identity primary key,
  room_type_id bigint not null references public.room_types(id) on delete cascade,
  storage_path text not null,
  alt_text text not null default '',
  is_primary boolean not null default false,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint room_images_storage_path_key unique (storage_path),
  constraint room_images_storage_path_not_blank check (btrim(storage_path) <> '')
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  confirmation_code text not null,
  room_type_id bigint not null references public.room_types(id) on delete restrict,
  guest_first_name text not null,
  guest_last_name text not null,
  guest_email text not null,
  guest_phone text not null,
  arrival_date date not null,
  departure_date date not null,
  status text not null default 'pending',
  nightly_rate numeric(10, 2) not null,
  total_amount numeric(12, 2) not null,
  currency text not null default 'USD',
  admin_notes text,
  status_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bookings_confirmation_code_key unique (confirmation_code),
  constraint bookings_confirmation_code_format check (confirmation_code ~ '^NYK-[A-F0-9]{10}$'),
  constraint bookings_guest_first_name_not_blank check (btrim(guest_first_name) <> ''),
  constraint bookings_guest_last_name_not_blank check (btrim(guest_last_name) <> ''),
  constraint bookings_guest_email_format check (
    guest_email = lower(guest_email)
    and guest_email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  constraint bookings_guest_phone_not_blank check (btrim(guest_phone) <> ''),
  constraint bookings_valid_stay check (departure_date > arrival_date),
  constraint bookings_status_valid check (
    status in ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')
  ),
  constraint bookings_rate_positive check (nightly_rate > 0),
  constraint bookings_total_positive check (total_amount > 0),
  constraint bookings_currency_format check (currency ~ '^[A-Z]{3}$')
);

create index room_types_active_display_order_idx
